"""The local SatQuery intent model: question text -> one operation label.

    classifier text -> IntentClassifier.predict() -> IntentPrediction

A small linear classifier - TF-IDF over word 1-2-grams and character 2-5-grams
(word-bounded), then multinomial logistic regression - trained by
``scripts/train_intent_model.py`` on the versioned dataset in
``data/intent/``. Its ONLY job is to name the operation a question asks for.
It computes nothing, chooses no raster, and never sees a coordinate or a date
as such: places and dates are replaced by ``PLACE`` / ``DATE`` before it reads
the question, and the deterministic reader stays authoritative for both.

**The artifact is data, never code.** Training exports the fitted pipeline to
one JSON document - vocabularies, IDF weights, coefficients - and this module
re-implements the two transforms and the softmax in numpy. There is no pickle
anywhere, so loading a model cannot execute anything, and production needs no
scikit-learn. The training script verifies that this implementation reproduces
scikit-learn's probabilities on every dataset example before it writes the
file, and ``tests/test_intent_model.py`` re-checks it.

**The artifact is untrusted input.** Every field is validated on load - format,
the exact label set, shapes, finiteness, sizes - and anything unexpected
refuses the whole model. A refused or missing model is not an outage: the
router then uses the rule-based interpreter alone, which is what M5.5 shipped.

**The output is untrusted too.** A prediction is an :class:`IntentPrediction`
whose label is a closed ``Literal`` and whose confidence is a finite
probability. There is no field that could carry a URL, a path, a command or a
route - only one of eight names and a number.

Purity: no network, no provider, no filesystem access beyond reading the one
artifact file. Imports are stdlib, numpy and pydantic - enforced by a test.
"""

from __future__ import annotations

import gzip
import json
import math
import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any, Literal, get_args

import numpy as np
from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.core.logging import get_logger

logger = get_logger("agent.intent_model")

#: The operations the model may name. Exactly the backend's capabilities plus
#: the two refusals; nothing is listed that the engines cannot do.
IntentLabel = Literal[
    "NDVI",
    "NDWI",
    "NDBI",
    "SAR_BACKSCATTER",
    "TEMPORAL_NDWI",
    "TRUE_COLOR",
    "CLARIFICATION",
    "UNSUPPORTED",
]
INTENT_LABELS: tuple[str, ...] = get_args(IntentLabel)

ARTIFACT_FORMAT = "satquery-intent-model"
ARTIFACT_FORMAT_VERSION = 1

#: The shipped artifact. Generated by ``scripts/train_intent_model.py``.
DEFAULT_ARTIFACT = Path(__file__).parent / "intent_artifacts" / "satquery_intent_v2.json.gz"

#: Refuse an artifact larger than this many features or bytes: a model this
#: size needs tens of thousands, and nothing legitimate needs millions.
_MAX_FEATURES = 500_000
_MAX_ARTIFACT_BYTES = 20_000_000

# The two text transforms, exactly as scikit-learn defines them for the
# configuration training uses (lowercase, no accent stripping, default token
# pattern, char_wb). Changing either here without retraining is caught by the
# equivalence test.
_TOKEN = re.compile(r"(?u)\b\w\w+\b")
_WHITE_SPACES = re.compile(r"\s\s+")


class IntentModelError(ValueError):
    """The artifact is missing, malformed or not one this build understands."""


class IntentPrediction(BaseModel):
    """What the model said: one closed label and how sure it was.

    Validated like any other untrusted output. ``extra="forbid"`` and the
    ``Literal`` label mean nothing else can be carried through it.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    label: IntentLabel
    confidence: float = Field(ge=0.0, le=1.0)

    @field_validator("confidence")
    @classmethod
    def _finite(cls, value: float) -> float:
        if not math.isfinite(value):
            raise ValueError("confidence must be finite")
        return value


def _word_ngrams(text: str, ngram_range: tuple[int, int]) -> list[str]:
    tokens = _TOKEN.findall(text.lower())
    min_n, max_n = ngram_range
    grams: list[str] = []
    for n in range(min_n, max_n + 1):
        for i in range(len(tokens) - n + 1):
            grams.append(" ".join(tokens[i : i + n]))
    return grams


def _char_wb_ngrams(text: str, ngram_range: tuple[int, int]) -> list[str]:
    """scikit-learn's ``char_wb`` analyzer: n-grams inside space-padded words."""

    text = _WHITE_SPACES.sub(" ", text.lower())
    min_n, max_n = ngram_range
    grams: list[str] = []
    for word in text.split():
        padded = f" {word} "
        length = len(padded)
        for n in range(min_n, max_n + 1):
            offset = 0
            grams.append(padded[offset : offset + n])
            while offset + n < length:
                offset += 1
                grams.append(padded[offset : offset + n])
            if offset == 0:  # a word shorter than n is counted once
                break
    return grams


@dataclass(frozen=True)
class _TfidfBlock:
    """One fitted TF-IDF transform: vocabulary, IDF, sublinear TF, L2 norm."""

    analyzer: str
    ngram_range: tuple[int, int]
    index: dict[str, int]
    idf: np.ndarray

    def transform(self, text: str) -> tuple[np.ndarray, np.ndarray]:
        """Column indices and values of the one-row TF-IDF vector."""

        grams = (
            _word_ngrams(text, self.ngram_range)
            if self.analyzer == "word"
            else _char_wb_ngrams(text, self.ngram_range)
        )
        counts: dict[int, int] = {}
        for gram in grams:
            column = self.index.get(gram)
            if column is not None:
                counts[column] = counts.get(column, 0) + 1
        if not counts:
            return np.empty(0, dtype=np.int64), np.empty(0, dtype=np.float64)
        columns = np.fromiter(counts.keys(), dtype=np.int64, count=len(counts))
        tf = np.fromiter(counts.values(), dtype=np.float64, count=len(counts))
        values = (1.0 + np.log(tf)) * self.idf[columns]
        norm = float(np.sqrt(np.dot(values, values)))
        return columns, (values / norm if norm > 0 else values)


class IntentClassifier:
    """The loaded model. Construct through :func:`load_intent_classifier`."""

    def __init__(
        self,
        *,
        labels: tuple[str, ...],
        blocks: tuple[_TfidfBlock, ...],
        coef: np.ndarray,
        intercept: np.ndarray,
        threshold: float,
        version: str,
        metadata: dict[str, Any],
    ) -> None:
        self.labels = labels
        self._blocks = blocks
        self._coef = coef
        self._intercept = intercept
        #: The confidence below which a prediction is not acted on. Chosen on
        #: the validation split when this artifact was trained, and shipped
        #: WITH it, because a threshold is only meaningful for its own model.
        self.threshold = threshold
        self.version = version
        self.metadata = metadata

    def probabilities(self, text: str) -> np.ndarray:
        """Softmax over the labels, in ``self.labels`` order."""

        scores = self._intercept.copy()
        offset = 0
        for block in self._blocks:
            columns, values = block.transform(text)
            if columns.size:
                scores += self._coef[:, offset + columns] @ values
            offset += len(block.index)
        scores -= scores.max()
        exp = np.exp(scores)
        return exp / exp.sum()

    def predict(self, text: str) -> IntentPrediction:
        """The most probable label, validated before it leaves this module."""

        probabilities = self.probabilities(text)
        best = int(np.argmax(probabilities))
        return IntentPrediction(
            label=self.labels[best],  # type: ignore[arg-type]
            confidence=float(probabilities[best]),
        )


