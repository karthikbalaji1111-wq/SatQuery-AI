def _require(condition: bool, message: str) -> None:
    if not condition:
        raise IntentModelError(message)


def _finite_vector(raw: Any, length: int | None, name: str) -> np.ndarray:
    _require(isinstance(raw, list), f"{name} must be a list")
    array = np.asarray(raw, dtype=np.float64)
    _require(array.ndim == 1, f"{name} must be one-dimensional")
    if length is not None:
        _require(array.shape[0] == length, f"{name} has the wrong length")
    _require(bool(np.all(np.isfinite(array))), f"{name} must be finite")
    return array


def _ngram_range(raw: Any, name: str) -> tuple[int, int]:
    _require(
        isinstance(raw, list) and len(raw) == 2 and all(type(v) is int for v in raw),
        f"{name}.ngram_range must be two integers",
    )
    low, high = raw
    _require(1 <= low <= high <= 8, f"{name}.ngram_range is out of bounds")
    return low, high


def _block(raw: Any, name: str, analyzer: str) -> _TfidfBlock:
    _require(isinstance(raw, dict), f"{name} must be an object")
    _require(raw.get("analyzer") == analyzer, f"{name}.analyzer must be {analyzer!r}")
    vocabulary = raw.get("vocabulary")
    _require(
        isinstance(vocabulary, list) and all(isinstance(t, str) for t in vocabulary),
        f"{name}.vocabulary must be a list of strings",
    )
    _require(len(vocabulary) == len(set(vocabulary)), f"{name}.vocabulary has duplicates")
    idf = _finite_vector(raw.get("idf"), len(vocabulary), f"{name}.idf")
    _require(bool(np.all(idf > 0)), f"{name}.idf must be positive")
    return _TfidfBlock(
        analyzer=analyzer,
        ngram_range=_ngram_range(raw.get("ngram_range"), name),
        index={term: position for position, term in enumerate(vocabulary)},
        idf=idf,
    )


def parse_artifact(document: Any) -> IntentClassifier:
    """Build a classifier from an artifact document, or refuse it."""

    _require(isinstance(document, dict), "the artifact must be a JSON object")
    _require(document.get("format") == ARTIFACT_FORMAT, "not a SatQuery intent model")
    _require(
        document.get("format_version") == ARTIFACT_FORMAT_VERSION,
        "unsupported intent model format version",
    )
    labels = document.get("labels")
    _require(
        isinstance(labels, list) and sorted(labels) == sorted(INTENT_LABELS)
        and len(labels) == len(INTENT_LABELS),
        "the artifact's labels must be exactly the supported intents",
    )
    features = document.get("features")
    _require(isinstance(features, dict), "features must be an object")
    blocks = (
        _block(features.get("word"), "features.word", "word"),
        _block(features.get("char"), "features.char", "char_wb"),
    )
    width = sum(len(block.index) for block in blocks)
    _require(0 < width <= _MAX_FEATURES, "the feature count is out of bounds")

    classifier = document.get("classifier")
    _require(isinstance(classifier, dict), "classifier must be an object")
    coef_raw = classifier.get("coef")
    _require(
        isinstance(coef_raw, list) and len(coef_raw) == len(labels),
        "coef must have one row per label",
    )
    coef = np.vstack([_finite_vector(row, width, "coef row") for row in coef_raw])
    intercept = _finite_vector(classifier.get("intercept"), len(labels), "intercept")

    threshold = document.get("threshold")
    _require(
        isinstance(threshold, (int, float)) and not isinstance(threshold, bool)
        and math.isfinite(threshold) and 0.0 < threshold < 1.0,
        "threshold must be a probability strictly between 0 and 1",
    )
    version = document.get("model_version")
    _require(
        isinstance(version, str) and re.fullmatch(r"[A-Za-z0-9._-]{1,64}", version) is not None,
        "model_version must be a short identifier",
    )
    metadata = document.get("metadata")
    _require(isinstance(metadata, dict), "metadata must be an object")

    return IntentClassifier(
        labels=tuple(labels),
        blocks=blocks,
        coef=coef,
        intercept=intercept,
        threshold=float(threshold),
        version=version,
        metadata=metadata,
    )


def read_artifact(path: Path) -> IntentClassifier:
    """Read and validate an artifact file (gzip-compressed or plain JSON)."""

    raw = path.read_bytes()
    _require(len(raw) <= _MAX_ARTIFACT_BYTES, "the artifact file is too large")
    if raw[:2] == b"\x1f\x8b":
        raw = gzip.decompress(raw)
        _require(len(raw) <= 5 * _MAX_ARTIFACT_BYTES, "the artifact expands too far")
    try:
        document = json.loads(raw)
    except ValueError as exc:
        raise IntentModelError("the artifact is not valid JSON") from exc
    return parse_artifact(document)


@lru_cache(maxsize=1)
def load_intent_classifier(path: Path | None = None) -> IntentClassifier | None:
    """The shipped model, loaded once per process - or ``None``.

    ``None`` is a supported state, not an error: the router then interprets
    with the rules alone. The reason is logged by class, never by content.
    """

    target = path or DEFAULT_ARTIFACT
    try:
        classifier = read_artifact(target)
    except (OSError, IntentModelError, ValueError) as exc:
        logger.warning(
            "Intent model unavailable (%s); interpreting with the rules alone",
            type(exc).__name__,
        )
        return None
    logger.info(
        "Intent model %s loaded (%d labels, threshold %.2f)",
        classifier.version,
        len(classifier.labels),
        classifier.threshold,
    )
    return classifier
